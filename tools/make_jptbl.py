"""Write tbl/jp.tbl from the EXE (docs/re/text.md §Encoding): control codes, ASCII (txd markup text only),
the single-byte hiragana table at EXE file 0x1B0C (codes 0xA6-0xDD), and every valid Shift-JIS pair.

    python -X utf8 tools/make_jptbl.py work/disc1/tree/SLPS_012.97 tbl/jp.tbl

Single-byte hiragana duplicate SJIS hiragana; tbl.py encodes each character to one canonical code, so phase 4 must
escape the other form ([XX]) to keep encode(decode()) exact.
"""
import struct
import sys

HIRA_TABLE = 0x1B0C  # 0x38 x u16 SJIS codes for bytes 0xA6..0xDD


def lines(exe):
    out = ["# Guardian Recall: generated by tools/make_jptbl.py; do not edit by hand",
           "00={end}", "01={wait}", "0A={nl}", "0D={cr}", "20=\\s"]
    out += [f"{c:02X}={chr(c)}" for c in range(0x21, 0x7F)]
    for i in range(0x38):
        code = struct.unpack_from("<H", exe, HIRA_TABLE + 2 * i)[0]
        out.append(f"{0xA6 + i:02X}={code.to_bytes(2, 'big').decode('cp932')}")
    for lead in list(range(0x81, 0xA0)) + list(range(0xE0, 0xF0)):
        for trail in list(range(0x40, 0x7F)) + list(range(0x80, 0xFD)):
            try:
                ch = bytes([lead, trail]).decode("cp932")
            except UnicodeDecodeError:
                continue
            if (ch.isprintable() or ch == "　") and ch not in "=#":
                out.append(f"{lead:02X}{trail:02X}={ch}")
    return out


if __name__ == "__main__":
    exe = open(sys.argv[1], "rb").read()
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines(exe)) + "\n")
